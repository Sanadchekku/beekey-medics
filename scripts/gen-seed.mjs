// Generates supabase/seed.sql — the sample partners (doctors, labs, medical shops, riders)
// from js/data.js, so the database and the app's built-in demo data never drift apart.
// Run: npm run db:seed-sql   (safe to re-run; existing rows are left as they are)
import fs from 'node:fs';
import { seedNetwork } from '../js/data.js';

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const rows = [];
for (const [role, list] of Object.entries(seedNetwork())) for (const p of list) rows.push(`  (${q(p.id)}, ${q(role)}, ${q(JSON.stringify(p))}::jsonb)`);

const sql = `-- Sample partner network for testing (generated by scripts/gen-seed.mjs — do not edit by hand).
-- Branches: Kochi, Pune (Kharadi) and Perinthalmanna. Re-running it never overwrites admin edits.
insert into public.partners (id, role, data) values
${rows.join(',\n')}
on conflict (id) do nothing;
`;
fs.writeFileSync('supabase/seed.sql', sql);
console.log(`supabase/seed.sql: ${rows.length} partners`);
